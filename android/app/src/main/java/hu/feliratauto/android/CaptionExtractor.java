package hu.feliratauto.android;
import android.content.Context;

import org.json.JSONArray;
import org.json.JSONObject;
import org.schabi.newpipe.extractor.MediaFormat;
import org.schabi.newpipe.extractor.NewPipe;
import org.schabi.newpipe.extractor.localization.Localization;
import org.schabi.newpipe.extractor.localization.ContentCountry;
import org.schabi.newpipe.extractor.stream.StreamExtractor;
import org.schabi.newpipe.extractor.stream.SubtitlesStream;
import java.util.Comparator;
import java.util.List;

final class CaptionExtractor {
    private final DeviceDownloader downloader = new DeviceDownloader();
    private final Context context;
    CaptionExtractor(Context context) {
        this.context = context.getApplicationContext();
        NewPipe.init(downloader, new Localization("en", "GB"), new ContentCountry("GB"));
    }

    static int rank(String language, boolean auto, String preferred) {
        String code = language.toLowerCase(java.util.Locale.ROOT);
        String wanted = preferred.toLowerCase(java.util.Locale.ROOT);
        if (!wanted.isEmpty() && (code.equals(wanted) || code.startsWith(wanted + "-"))) return auto ? 1 : 0;
        if (code.equals("en") || code.startsWith("en-")) return auto ? 3 : 2;
        if (code.equals("hu") || code.startsWith("hu-")) return 4;
        return auto ? 6 : 5;
    }

    JSONObject extract(String videoId, String preferred, LocalSpeech.Progress progress) throws Exception {
        JSONObject cached = SpeechSource.cached(context, videoId);
        if (cached != null) return cached;
        StreamExtractor extractor = NewPipe.getService("YouTube").getStreamExtractor("https://www.youtube.com/watch?v=" + videoId);
        extractor.fetchPage();
        List<SubtitlesStream> subtitles = extractor.getSubtitles(MediaFormat.VTT);
        if (subtitles.isEmpty()) return SpeechSource.create(context, extractor, videoId, progress);
        SubtitlesStream chosen = subtitles.stream().min(Comparator.comparingInt(track -> rank(track.getLanguageTag(), track.isAutoGenerated(), preferred))).orElseThrow();
        String vtt = chosen.getContent();
        if (chosen.isUrl()) {
            var response = downloader.get(vtt);
            if (response.responseCode() == 429 || response.responseCode() == 403) {
                throw new CaptionFailure("youtube_blocked", "A YouTube a telefon feliratkérését is korlátozta. Próbáld újra később.");
            }
            if (response.responseCode() != 200) throw new CaptionFailure("download_failed", "A feliratsáv nem tölthető le (HTTP " + response.responseCode() + ").");
            vtt = response.responseBody();
        }
        if (vtt.trim().isEmpty()) throw new CaptionFailure("download_failed", "Megérkezett a feliratsáv címe, de a YouTube üres feliratot adott vissza.");
        if (vtt.length() > 2 * 1024 * 1024) throw new CaptionFailure("too_large", "Ez a felirat meghaladja a két megabájtos méretkorlátot.");
        JSONArray tracks = new JSONArray();
        for (SubtitlesStream track : subtitles) tracks.put(trackInfo(track));
        return new JSONObject().put("videoId", videoId).put("title", extractor.getName())
            .put("source", "android").put("selectedTrack", trackInfo(chosen))
            .put("tracks", tracks).put("vtt", vtt).put("nativeVersion", BuildConfig.VERSION_NAME);
    }

    private JSONObject trackInfo(SubtitlesStream track) throws Exception {
        return new JSONObject().put("langCode", track.getLanguageTag())
            .put("langName", track.getName() == null ? track.getDisplayLanguageName() : track.getName())
            .put("isAuto", track.isAutoGenerated());
    }

    static final class CaptionFailure extends Exception {
        final String reason;
        CaptionFailure(String reason, String message) { super(message); this.reason = reason; }
    }
}
